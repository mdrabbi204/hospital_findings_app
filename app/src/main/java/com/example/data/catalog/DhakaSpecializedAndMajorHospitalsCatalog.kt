internal fun buildDhakaHospital(
    id: String,
    name: String,
    nameBn: String,
    type: FacilityType,
    area: String,
    address: String,
    lat: Double,
    lng: Double,
    phone: String,
    description: String,
    departments: List<String>,
    amenities: List<String>,
    rating: Double = 4.5,
    reviews: Int = 210,
    er247: Boolean = true,
    icu: Boolean = true,
    ccu: Boolean = false,
    nicu: Boolean = false,
    ambulance: Boolean = true,
    bloodBank: Boolean = false,
    popular: Boolean = false
) = Hospital(
    id = id,
    name = name,
    nameBn = nameBn,
    type = type,
    description = description,
    address = address,
    area = area,
    district = "Dhaka",
    division = "Dhaka",
    latitude = lat,
    longitude = lng,
    phone = phone,
    emergencyPhone = phone,
    website = "https://${id.removePrefix("hosp_")}.medcare-bd.org",
    email = "info@${id.removePrefix("hosp_")}.medcare-bd.org",
    operatingHours = if (er247) "Open 24 Hours" else "7:30 AM - 10:30 PM Daily",
    hasEmergency247 = er247,
    hasIcu = icu,
    hasCcu = ccu,
    hasNicu = nicu,
    hasAmbulance = ambulance,
    hasBloodBank = bloodBank,
    verified = true,
    rating = rating,
    reviewCount = reviews,
    departments = departments,
    amenities = amenities,
    isPopular = popular
)


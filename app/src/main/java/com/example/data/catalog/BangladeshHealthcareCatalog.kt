    internal fun buildWeeklySchedule(
        openDays: Set<Int>, // 1=Sat, 2=Sun, 3=Mon, 4=Tue, 5=Wed, 6=Thu, 7=Fri
        startTime: String,
        endTime: String,
        breakSlot: String?,
        slots: List<String>,
        holidayNote: String? = "Weekly Chamber Off"
    ): List<DayChamberSchedule> {
        val labels = listOf(
            1 to "Sat", 2 to "Sun", 3 to "Mon", 4 to "Tue", 5 to "Wed", 6 to "Thu", 7 to "Fri"
        )
        return labels.map { (idx, short) ->
            val isOpen = idx in openDays
            DayChamberSchedule(
                weekdayIndex = idx,
                weekdayShort = short,
                isOpen = isOpen,
                startTime24h = if (isOpen) startTime else "--:--",
                endTime24h = if (isOpen) endTime else "--:--",
                breakWindow = if (isOpen && breakSlot != null) "$breakSlot (Prayer/Break)" else "No break",
                slotDurationMins = 20,
                slots = if (!isOpen) {
                    listOf(ScheduleSlot("Closed", SlotStatus.CLOSED))
                } else {
                    slots.mapIndexed { sIdx, time ->
                        when {
                            breakSlot != null && time == breakSlot -> ScheduleSlot(time, SlotStatus.BREAK)
                            (idx + sIdx) % 5 == 3 -> ScheduleSlot(time, SlotStatus.BOOKED)
                            else -> ScheduleSlot(time, SlotStatus.AVAILABLE)
                        }
                    }
                },
                holidayNote = if (!isOpen) holidayNote else null
            )
        }
    }

